# 数据输出格式化（来自351_fd_to_tec）
# =============================================================================
def write_ascii_data(filename: str, headers: List[str],
                       data: np.ndarray, title: str = "Simulation Output"):
    """
    将模拟数据写入ASCII文件

    格式类似TECPLOT ASCII，但简化为纯文本格式

    参数:
        filename: 输出文件名
        headers: 列标题
        data: shape (n_rows, n_cols) 数据矩阵
        title: 标题
    """
    with open(filename, 'w') as f:
        f.write(f"# {title}\n")
        f.write(f"# Generated by edge_plasma_divertor_transport\n")
        f.write(f"# Columns: {', '.join(headers)}\n")
        f.write(f"# Rows: {data.shape[0]}\n")
        f.write("#" + "-" * 60 + "\n")

        for row in data:
            line = "  ".join(f"{v:16.8e}" for v in row)
            f.write(line + "\n")


def write_simulation_summary(filename: str, summary: Dict):
    """
    写入模拟摘要报告

    参数:
        filename: 输出文件名
        summary: 摘要字典
    """
    with open(filename, 'w') as f:
        f.write("=" * 70 + "\n")
        f.write(" 边界等离子体输运与偏滤器热负荷模拟 - 摘要报告\n")
        f.write(" Edge Plasma Transport & Divertor Heat Flux Simulation Summary\n")
        f.write("=" * 70 + "\n\n")

        for key, value in summary.items():
            if isinstance(value, float):
                f.write(f"  {key:40s}: {value:16.8e}\n")
            elif isinstance(value, int):
                f.write(f"  {key:40s}: {value:10d}\n")
            elif isinstance(value, str):
                f.write(f"  {key:40s}: {value}\n")
            elif isinstance(value, dict):
                f.write(f"\n  [{key}]\n")
                for k2, v2 in value.items():
                    if isinstance(v2, float):
                        f.write(f"    {k2:38s}: {v2:16.8e}\n")
                    else:
                        f.write(f"    {k2:38s}: {v2}\n")
            elif isinstance(value, np.ndarray):
                f.write(f"  {key:40s}: array shape={value.shape}\n")
            else:
                f.write(f"  {key:40s}: {value}\n")

        f.write("\n" + "=" * 70 + "\n")


