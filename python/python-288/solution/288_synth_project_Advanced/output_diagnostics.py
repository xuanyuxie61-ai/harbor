# 收敛历史追踪
# =============================================================================
class ConvergenceTracker:
    """
    追踪迭代求解器的收敛历史
    """

    def __init__(self):
        self.iterations = []
        self.residuals = []
        self.fidelities = []
        self.errors_L2 = []
        self.errors_H1 = []
        self.mass_errors = []

    def record(self, iteration: int, residual: float,
                fidelity: float = None, error_L2: float = None,
                error_H1: float = None, mass_error: float = None):
        """记录一步的收敛数据"""
        self.iterations.append(iteration)
        self.residuals.append(residual)
        if fidelity is not None:
            self.fidelities.append(fidelity)
        if error_L2 is not None:
            self.errors_L2.append(error_L2)
        if error_H1 is not None:
            self.errors_H1.append(error_H1)
        if mass_error is not None:
            self.mass_errors.append(mass_error)

    def get_convergence_rate(self) -> float:
        """
        估计收敛速率

        rate ≈ log(r_n / r_0) / n
        """
        if len(self.residuals) < 2:
            return 0.0

        r0 = self.residuals[0]
        rn = self.residuals[-1]
        n = len(self.residuals) - 1

        if r0 < 1e-30 or rn < 1e-30:
            return 0.0

        rate = np.log(rn / r0) / n
        return float(rate)

    def to_dict(self) -> Dict:
        """转换为字典"""
        return {
            'iterations': np.array(self.iterations),
            'residuals': np.array(self.residuals),
            'fidelities': np.array(self.fidelities) if self.fidelities else None,
            'errors_L2': np.array(self.errors_L2) if self.errors_L2 else None,
            'errors_H1': np.array(self.errors_H1) if self.errors_H1 else None,
            'mass_errors': np.array(self.mass_errors) if self.mass_errors else None,
        }

    def write_to_file(self, filename: str):
        """写入收敛历史到文件"""
        data = np.column_stack([
            np.array(self.iterations),
            np.array(self.residuals),
        ])
        headers = ['iteration', 'residual']
        write_ascii_data(filename, headers, data, "Convergence History")


